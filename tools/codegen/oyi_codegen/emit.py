"""Emitters: generated C++ header, schema JSON, Luau type definitions and Ninja/Make depfile."""

from __future__ import annotations

import json
import os

from oyi_codegen import __version__, hashing
from oyi_codegen.model import FieldDecl, FieldKind, HeaderSchema, RecordDecl

_CORE = "::oyi::core::"


def _float_literal(value: float) -> str:
    text = repr(float(value))
    if "e" in text or "E" in text:
        text = f"{value:.17g}"
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def _flags_expr(enum: str, flags: list[str]) -> str:
    if not flags:
        return f"{_CORE}{enum}::None"
    return " | ".join(f"{_CORE}{enum}::{f}" for f in flags)


def _field_initializer(f: FieldDecl) -> str:
    return (
        "{"
        f'.mName = "{f.name}", .mTypeName = "{f.type_name}", .mOffset = {f.offset}, .mSize = {f.size}, '
        f".mCount = {f.count}, .mKind = {_CORE}FieldKind::{f.kind.value}, "
        f".mFlags = {_flags_expr('FieldFlags', f.flags)}, .mTypeId = {_CORE}TypeId{{.mValue = {f.type_id:#018x}ull}}, "
        f".mQuantize = {_float_literal(f.quantize)}"
        "}"
    )


def _record_cpp(r: RecordDecl) -> list[str]:
    lines: list[str] = []
    fields_symbol = f"k{r.name}Fields"
    info_symbol = f"k{r.name}Info"
    if r.fields:
        lines.append(f"inline constexpr {_CORE}FieldInfo {fields_symbol}[] = {{")
        for f in r.fields:
            lines.append(f"    {_field_initializer(f)},")
        lines.append("};")
    fields_span = fields_symbol if r.fields else "{}"
    default_symbol = f"k{r.name}Default"
    lines.append(f"inline constexpr {r.name} {default_symbol}{{}};")
    lines.append(
        f"inline constexpr {_CORE}ComponentInfo {info_symbol}{{"
        f'.mName = "{r.qualified_name}", .mTypeId = {_CORE}TypeId{{.mValue = {r.type_id:#018x}ull}}, '
        f".mSize = {r.size}, .mAlign = {r.align}, .mFlags = {_flags_expr('ComponentFlags', r.flags)}, "
        f".mFields = {fields_span}, .mLayoutHash = {r.layout_hash:#018x}ull, .mDefault = &{default_symbol}}};"
    )
    drift = f'"oyi_codegen: layout of {r.qualified_name} changed since generation; rebuild to regenerate"'
    lines.append(f"static_assert(sizeof({r.name}) == {r.size}, {drift});")
    lines.append(f"static_assert(alignof({r.name}) == {r.align}, {drift});")
    for f in r.fields:
        lines.append(f"static_assert(offsetof({r.name}, {f.name}) == {f.offset}, {drift});")
    lines.append(
        f'static_assert({_CORE}MakeTypeId("{r.qualified_name}") == {info_symbol}.mTypeId, '
        '"oyi_codegen: TypeId hash differs between Python and C++");'
    )
    return lines


def render_header(schema: HeaderSchema) -> str:
    out: list[str] = [
        f"// Generated by oyi_codegen {__version__} from <{schema.header}>. Do not edit; rebuild to regenerate.",
        "#pragma once",
        "",
        f"#include <{schema.header}>",
        "#include <oyi_core/Schema.h>",
        "",
        "#include <cstddef>",
        "",
    ]
    by_namespace: dict[tuple[str, ...], list[RecordDecl]] = {}
    for r in schema.records:
        by_namespace.setdefault(r.namespace, []).append(r)
    for ns, records in by_namespace.items():
        ns_text = "::".join(ns)
        if ns_text:
            out.append(f"namespace {ns_text} {{")
            out.append("")
        for r in records:
            out.extend(_record_cpp(r))
            out.append("")
        if ns_text:
            out.append(f"}} // namespace {ns_text}")
            out.append("")
    # The header's schema hash, in the namespace of its first record (ADR-0011: schema hash).
    if schema.records:
        owner = "::".join(schema.records[0].namespace)
        if owner:
            out.append(f"namespace {owner} {{")
            out.append("")
        out.append("/// FNV-1a over the name, TypeId and layout hash of every record in this header.")
        out.append(f"inline constexpr unsigned long long kSchemaHash = {hashing.schema_hash(schema.records):#018x}ull;")
        out.append("")
        if owner:
            out.append(f"}} // namespace {owner}")
            out.append("")
    components = list(schema.records)
    if components:
        out.append("namespace oyi::core {")
        out.append("")
        for r in components:
            owner = "::".join(r.namespace)
            info = f"::{owner}::k{r.name}Info" if owner else f"::k{r.name}Info"
            out.append("template <>")
            out.append(f"struct ComponentTraits<::{r.qualified_name}> {{")
            out.append(f"    static constexpr const ComponentInfo& kInfo = {info};")
            out.append("};")
            out.append("")
        out.append("} // namespace oyi::core")
        out.append("")
    return "\n".join(out)


def render_json(schema: HeaderSchema) -> str:
    def field_json(f: FieldDecl) -> dict:
        data: dict = {
            "name": f.name,
            "type": f.type_name,
            "kind": f.kind.value,
            "offset": f.offset,
            "size": f.size,
            "count": f.count,
            "flags": f.flags,
        }
        if f.kind in (FieldKind.ENUM, FieldKind.STRUCT):
            data["typeName"] = f.type_qualified
            data["typeId"] = f"{f.type_id:#018x}"
        if f.quantize:
            data["quantize"] = f.quantize
        return data

    doc = {
        "generator": f"oyi_codegen {__version__}",
        "header": schema.header,
        "schemaHash": f"{hashing.schema_hash(schema.records):#018x}",
        "records": [
            {
                "name": r.qualified_name,
                "kind": r.kind,
                "typeId": f"{r.type_id:#018x}",
                "size": r.size,
                "align": r.align,
                "flags": r.flags,
                "layoutHash": f"{r.layout_hash:#018x}",
                "fields": [field_json(f) for f in r.fields],
            }
            for r in schema.records
        ],
    }
    return json.dumps(doc, indent=2) + "\n"


_LUAU_SCALARS = {
    FieldKind.BOOL: "boolean",
    FieldKind.INT8: "number",
    FieldKind.UINT8: "number",
    FieldKind.INT16: "number",
    FieldKind.UINT16: "number",
    FieldKind.INT32: "number",
    FieldKind.UINT32: "number",
    FieldKind.INT64: "number",
    FieldKind.UINT64: "number",
    FieldKind.FLOAT32: "number",
    FieldKind.FLOAT64: "number",
    FieldKind.ENUM: "number",
}
_LUAU_ENTITY_TYPES = ("oyi::ecs::EntityId", "oyi::core::Handle<oyi::ecs::EntityTag>")


def _luau_type_names(schema: HeaderSchema) -> dict[int, str]:
    """Record type id -> Luau type name; the bare record name unless two records share it."""
    counts: dict[str, int] = {}
    for r in schema.records:
        counts[r.name] = counts.get(r.name, 0) + 1
    names: dict[int, str] = {}
    for r in schema.records:
        names[r.type_id] = r.name if counts[r.name] == 1 else "_".join((*r.namespace, r.name))
    return names


def _luau_field_type(f: FieldDecl, names: dict[int, str]) -> str:
    if f.kind is FieldKind.STRUCT:
        if f.type_name in _LUAU_ENTITY_TYPES or f.type_qualified in _LUAU_ENTITY_TYPES:
            base = "Entity"
        elif f.type_id in names:
            base = names[f.type_id]
        else:
            base = "Handle"  # another 64-bit handle; opaque to scripts
    else:
        base = _LUAU_SCALARS[f.kind]
    return f"{{ {base} }}" if f.count > 1 else base


def render_luau_types(schema: HeaderSchema) -> str:
    """A Luau module of `export type`s mirroring what the oyi bindings marshal (ADR-0012): the full
    shape for oyi.get / oyi.prev and a partial one for oyi.set / oyi.send. Entity and Handle come
    from engine/oyi_script/luau/oyi.d.luau."""
    names = _luau_type_names(schema)
    out: list[str] = [
        f"-- Generated by oyi_codegen {__version__} from <{schema.header}>. Do not edit; rebuild to regenerate.",
        "-- Table shapes of the reflected records: <Name> for oyi.get / oyi.prev, <Name>Partial for",
        "-- oyi.set / oyi.send. Entity and Handle are declared by oyi.d.luau.",
        "--!strict",
        "",
    ]
    for r in schema.records:
        name = names[r.type_id]
        fields = [f for f in r.fields if not f.is_padding]
        if not fields:
            out.append(f"export type {name} = {{}}")
            out.append(f"export type {name}Partial = {{}}")
            out.append("")
            continue
        out.append(f"export type {name} = {{")
        for f in fields:
            out.append(f"    {f.name}: {_luau_field_type(f, names)},")
        out.append("}")
        out.append(f"export type {name}Partial = {{")
        for f in fields:
            out.append(f"    {f.name}: {_luau_field_type(f, names)}?,")
        out.append("}")
        out.append("")
    out.append("return {}")
    out.append("")
    return "\n".join(out)


def render_depfile(outputs: list[str], dependencies: list[str]) -> str:
    def escape(path: str) -> str:
        return os.path.abspath(path).replace("\\", "/").replace(" ", "\\ ")

    targets = " ".join(escape(o) for o in outputs)
    deps = " \\\n  ".join(escape(d) for d in dependencies)
    return f"{targets}: {deps}\n"
