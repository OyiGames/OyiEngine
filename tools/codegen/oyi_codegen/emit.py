"""Emitters: generated C++ header, schema JSON and Ninja/Make depfile."""

from __future__ import annotations

import json
import os

from oyi_codegen import __version__
from oyi_codegen.model import FieldDecl, FieldKind, HeaderSchema, RecordDecl

_CORE = "::oyi::core::"


def _float_literal(value: float) -> str:
    text = repr(float(value))
    if "e" in text or "E" in text:
        text = f"{value:.17g}"
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def _flags_expr(enum: str, flags: list[str]) -> str:
    if not flags:
        return f"{_CORE}{enum}::None"
    return " | ".join(f"{_CORE}{enum}::{f}" for f in flags)


def _field_initializer(f: FieldDecl) -> str:
    return (
        "{"
        f'.mName = "{f.name}", .mTypeName = "{f.type_name}", .mOffset = {f.offset}, .mSize = {f.size}, '
        f".mCount = {f.count}, .mKind = {_CORE}FieldKind::{f.kind.value}, "
        f".mFlags = {_flags_expr('FieldFlags', f.flags)}, .mTypeId = {_CORE}TypeId{{.mValue = {f.type_id:#018x}ull}}, "
        f".mQuantize = {_float_literal(f.quantize)}"
        "}"
    )


def _record_cpp(r: RecordDecl) -> list[str]:
    lines: list[str] = []
    fields_symbol = f"k{r.name}Fields"
    info_symbol = f"k{r.name}Info"
    if r.fields:
        lines.append(f"inline constexpr {_CORE}FieldInfo {fields_symbol}[] = {{")
        for f in r.fields:
            lines.append(f"    {_field_initializer(f)},")
        lines.append("};")
    fields_span = fields_symbol if r.fields else "{}"
    lines.append(
        f"inline constexpr {_CORE}ComponentInfo {info_symbol}{{"
        f'.mName = "{r.qualified_name}", .mTypeId = {_CORE}TypeId{{.mValue = {r.type_id:#018x}ull}}, '
        f".mSize = {r.size}, .mAlign = {r.align}, .mFlags = {_flags_expr('ComponentFlags', r.flags)}, "
        f".mFields = {fields_span}, .mLayoutHash = {r.layout_hash:#018x}ull}};"
    )
    drift = f'"oyi_codegen: layout of {r.qualified_name} changed since generation; rebuild to regenerate"'
    lines.append(f"static_assert(sizeof({r.name}) == {r.size}, {drift});")
    lines.append(f"static_assert(alignof({r.name}) == {r.align}, {drift});")
    for f in r.fields:
        lines.append(f"static_assert(offsetof({r.name}, {f.name}) == {f.offset}, {drift});")
    lines.append(
        f'static_assert({_CORE}MakeTypeId("{r.qualified_name}") == {info_symbol}.mTypeId, '
        '"oyi_codegen: TypeId hash differs between Python and C++");'
    )
    return lines


def render_header(schema: HeaderSchema) -> str:
    out: list[str] = [
        f"// Generated by oyi_codegen {__version__} from <{schema.header}>. Do not edit; rebuild to regenerate.",
        "#pragma once",
        "",
        f"#include <{schema.header}>",
        "#include <oyi_core/Schema.h>",
        "",
        "#include <cstddef>",
        "",
    ]
    by_namespace: dict[tuple[str, ...], list[RecordDecl]] = {}
    for r in schema.records:
        by_namespace.setdefault(r.namespace, []).append(r)
    for ns, records in by_namespace.items():
        ns_text = "::".join(ns)
        if ns_text:
            out.append(f"namespace {ns_text} {{")
            out.append("")
        for r in records:
            out.extend(_record_cpp(r))
            out.append("")
        if ns_text:
            out.append(f"}} // namespace {ns_text}")
            out.append("")
    return "\n".join(out)


def render_json(schema: HeaderSchema) -> str:
    def field_json(f: FieldDecl) -> dict:
        data: dict = {
            "name": f.name,
            "type": f.type_name,
            "kind": f.kind.value,
            "offset": f.offset,
            "size": f.size,
            "count": f.count,
            "flags": f.flags,
        }
        if f.kind in (FieldKind.ENUM, FieldKind.STRUCT):
            data["typeName"] = f.type_qualified
            data["typeId"] = f"{f.type_id:#018x}"
        if f.quantize:
            data["quantize"] = f.quantize
        return data

    doc = {
        "generator": f"oyi_codegen {__version__}",
        "header": schema.header,
        "records": [
            {
                "name": r.qualified_name,
                "kind": r.kind,
                "typeId": f"{r.type_id:#018x}",
                "size": r.size,
                "align": r.align,
                "flags": r.flags,
                "layoutHash": f"{r.layout_hash:#018x}",
                "fields": [field_json(f) for f in r.fields],
            }
            for r in schema.records
        ],
    }
    return json.dumps(doc, indent=2) + "\n"


def render_depfile(outputs: list[str], dependencies: list[str]) -> str:
    def escape(path: str) -> str:
        return os.path.abspath(path).replace("\\", "/").replace(" ", "\\ ")

    targets = " ".join(escape(o) for o in outputs)
    deps = " \\\n  ".join(escape(d) for d in dependencies)
    return f"{targets}: {deps}\n"
