"""Merges the schema JSON of every SDK module into the build schema (ADR-0024): oyi_schema.json for
tools, plus a C++ source that embeds the same text into the oyi executable."""

from __future__ import annotations

import json
import os

from oyi_codegen import __version__

_COMBINE_CONSTANT = 0x9E3779B97F4A7C15
_MASK64 = (1 << 64) - 1


def build_schema_hash(module_hashes: list[int]) -> int:
    """Boost-style combination in module order; must match GetBuildSchemaHash in tools/oyi."""
    value = 0
    for part in module_hashes:
        value ^= (part + _COMBINE_CONSTANT + ((value << 6) & _MASK64) + (value >> 2)) & _MASK64
        value &= _MASK64
    return value


def merge(paths: list[str]) -> dict:
    modules = []
    for path in paths:
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
        modules.append({"header": doc["header"], "schemaHash": doc["schemaHash"], "records": doc["records"]})
    combined = build_schema_hash([int(m["schemaHash"], 16) for m in modules])
    return {
        "generator": f"oyi_codegen {__version__}",
        "buildSchemaHash": f"{combined:#018x}",
        "modules": modules,
    }


def render_cpp(text: str) -> str:
    """The merged JSON as a char array (ASCII only, so no byte exceeds 127 and no cast is needed)."""
    data = text.encode("ascii")
    rows = []
    for i in range(0, len(data), 24):
        rows.append("    " + ", ".join(str(b) for b in data[i : i + 24]) + ",")
    body = "\n".join(rows)
    lines = [
        f"// Generated by oyi_codegen {__version__} (merge). Do not edit; rebuild to regenerate.",
        "#include <string_view>",
        "",
        "namespace oyi::cli {",
        "",
        "namespace {",
        "",
        "constexpr char kSchemaJson[] = {",
        body,
        "};",
        "",
        "} // namespace",
        "",
        "std::string_view GetBuildSchemaJson() noexcept {",
        "    return {kSchemaJson, sizeof(kSchemaJson)};",
        "}",
        "",
        "} // namespace oyi::cli",
        "",
    ]
    return "\n".join(lines)


def write_outputs(paths: list[str], out_json: str, out_cpp: str | None) -> None:
    doc = merge(paths)
    text = json.dumps(doc, indent=2) + "\n"
    os.makedirs(os.path.dirname(os.path.abspath(out_json)), exist_ok=True)
    with open(out_json, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)
    if out_cpp:
        os.makedirs(os.path.dirname(os.path.abspath(out_cpp)), exist_ok=True)
        with open(out_cpp, "w", encoding="ascii", newline="\n") as fh:
            fh.write(render_cpp(text))
